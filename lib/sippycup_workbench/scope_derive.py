"""Compile the scope file into derivatives and track their staleness.

Staleness model: ``scope-derivatives.json`` is a sidecar written next to the
derivatives. It records the scope file's SHA-256, and for every derivative its
path, its own SHA-256, and the scope hash it was generated from. The profile
and the campaign manifest reject unknown fields and the oracle loader rejects
unknown top-level keys, so no hash is embedded in the derivatives themselves.
The sidecar is an integrity aid for honest mistakes, not a tamper-proof seal.
"""

