SIDECAR_FILE = "scope-derivatives.json"
SIDECAR_VERSION = "sippycup.dev/scope-derivatives/v1"
COMPILE_VERSION = "sippycup.dev/scope-compile/v1"
FILENAMES = {
    PROFILE: "target-profile.yaml",
    CAMPAIGN: "campaign.yaml",
    EXPECTATIONS: "expectations.yaml",
}
# One profile per target. The first target keeps the name `status`, the
# cockpit, and every older document look for; each further target gets
# ``target-profile-TARGETNAME.yaml`` (the scope's ``targets[].name``), recorded
# in the sidecar under the key ``profile:TARGETNAME``.
PROFILE_KEY_PREFIX = f"{PROFILE}:"
# Files scope compile writes as a record only (no sender reads them). They are
# recorded in the sidecar by hash like the derivatives, so the report can tell
# the file compile wrote from an edited one; `derivative_state` leaves them
# out (the application record has its own state, `scope_app_derive.state_for`).
RECORD_ONLY = {"application-surfaces": "application-surfaces.yaml"}


def profile_filename(target_name: str | None) -> str:
    """The profile file of a target (``None``: the first target)."""
    return FILENAMES[PROFILE] if target_name is None else f"target-profile-{target_name}.yaml"


def profile_key(target_name: str | None) -> str:
    return PROFILE if target_name is None else f"{PROFILE_KEY_PREFIX}{target_name}"


def _key_target(key: str) -> str | None:
    """The target name of a further target's sidecar key, else ``None``."""
    if not key.startswith(PROFILE_KEY_PREFIX):
        return None
    name = key[len(PROFILE_KEY_PREFIX):]
    return name if TARGET_NAME_PATTERN.fullmatch(name) else None


HEADER = (
    "# Generated by `./bin/sippycup scope compile` from the private scope file.\n"
    "# Do not edit by hand: change the scope file and compile again. A hand edit is\n"
    "# reported as an edited derivative and blocks the next compile without --force.\n"
)


@dataclass
class CompileResult:
    report: Report
    generated: list[dict[str, str]] = field(default_factory=list)
    skipped: dict[str, list[Finding]] = field(default_factory=dict)
    refused: list[Finding] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    profile_status: str | None = None
    generated_at: str | None = None
    # How many files a clean compile writes: one profile per target, the
    # campaign manifest, and the expectations.
    expected: int = len(ARTIFACTS)
    # Profiles of targets that left the scope, removed by this compile.
    removed: list[str] = field(default_factory=list)
    application: dict[str, str] | None = None

    @property
    def exit_code(self) -> int:
        if self.report.fatal or self.refused:
            return 2
        if self.report.ok and len(self.generated) == self.expected:
            return 0
        return 1

    @property
    def profile_not_usable(self) -> str | None:
        """Why the profiles are written ``pending`` although the scope says approved, else None.

        ``_build_profile`` downgrades an approved scope that has errors, so the
        profile says pending. That is not the owner's answer: it is this scope
        error, and the operator should read the error, not "pending".
        """
        document = self.report.document or {}
        if (
            self.profile_status == "pending"
            and (document.get("authorization") or {}).get("status") == "approved"
            and self.report.errors
        ):
            first = self.report.errors[0]
            more = len(self.report.errors) - 1
            return f"{first.code} [{first.field}]: {first.message}" + (f" (and {more} more scope error(s))" if more else "")
        return None

    def as_dict(self) -> dict[str, Any]:
        return {
            "apiVersion": COMPILE_VERSION,
            "scope": {"path": self.report.path, "sha256": self.report.sha256},
            "ok": self.exit_code == 0,
            "profileStatus": self.profile_status,
            "profileNotUsable": self.profile_not_usable,
            "generated": self.generated,
            "skipped": {
                name: [item.as_dict() for item in items]
                for name, items in sorted(self.skipped.items())
            },
            "refused": [item.as_dict() for item in self.refused],
            "invalidScope": [item.as_dict() for item in self.report.findings] if self.report.fatal else [],
            "removed": self.removed,
            "notes": self.notes,
            "applicationSurfaces": self.application,
            "networkActivity": False,
        }


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _dump(document: dict[str, Any]) -> bytes:
    return (HEADER + yaml.safe_dump(document, sort_keys=False, default_flow_style=False)).encode()


def _iso(value: Any) -> str | None:
    if value is None:
        return None
    try:
        parsed = _parse_time(value, "time")
    except ProfileError:
        return None
    return parsed.isoformat() if parsed else None


def _approved_destinations(doc: dict[str, Any], target_name: str) -> list[str]:
    """The dial strings (``destinations[].user``) the scope lists for one target.

    Every destination counts, whatever it is expected to do (the owner
    approved dialing a destination that rejects too). Entries that are not
    valid are left out; ``scope check`` reports them and the profile is then
    pending. A scope with no destination for the target yields an empty list:
    that profile approves no call destination.
    """
    targets = doc.get("targets") or []
    result: list[str] = []
    for item in doc.get("destinations") or []:
        if not isinstance(item, dict):
            continue
        user = item.get("user")
        if not isinstance(user, str) or DESTINATION_PATTERN.fullmatch(user) is None:
            continue
        target = item.get("target")
        if target is None and len(targets) == 1:
            target = target_name
        if target == target_name and user not in result:
            result.append(user)
    return result


def _profile_name(scope_name: str, target_name: str | None) -> str:
    """The profile's display name: the scope name, plus the target for a further target."""
    if target_name is None:
        return scope_name
    return f"{scope_name[: 64 - len(target_name) - 1].rstrip('-')}-{target_name}"


def _build_profile(doc: dict[str, Any], report: Report, index: int = 0) -> dict[str, Any]:
    auth = doc.get("authorization") or {}
    status = auth.get("status")
    if status == "approved" and not report.ok:
        status = "pending"
    targets = normalized_targets(doc)
    first = targets[index]
    addresses: list[str] = []
    for item in targets:
        if item["address"] not in addresses:
            addresses.append(item["address"])
    for text in (doc.get("media") or {}).get("networks") or []:
        try:
            network = canonical_network(text)
        except ValueError:
            continue
        if network.prefixlen == network.max_prefixlen:
            literal = str(network.network_address)
            if literal not in addresses:
                addresses.append(literal)
    protection = doc["media"]["protection"]
    approved_by = auth.get("approved_by")
    approval_id = auth.get("approval_id")
    limits = doc["limits"]
    profile_target: dict[str, Any] = {
        "host": first["address"],
        "port": first["port"],
        "transport": first["transport"],
    }
    if first["transport"] == "tls":
        # The reviewed certificate name and trust anchor; the profile still
        # connects only to the literal host.
        if first.get("tls_server_name"):
            profile_target["tls_server_name"] = first["tls_server_name"]
        if first.get("tls_ca_file"):
            profile_target["tls_ca_file"] = first["tls_ca_file"]
    profile_target["approved_addresses"] = addresses
    profile_target["approved_destinations"] = _approved_destinations(doc, first["name"])
    return {
        "schema_version": PROFILE_VERSION,
        "name": _profile_name(doc["name"], first["name"] if index else None),
        "target": profile_target,
        "authorization": {
            "status": status,
            "approved_by": approved_by if isinstance(approved_by, str) else "",
            "approval_id": approval_id if isinstance(approval_id, str) else "",
            "valid_from": _iso(auth.get("valid_from")),
            "valid_until": _iso(auth.get("valid_until")),
        },
        "limits": {
            "max_calls": limits["calls"],
            "max_concurrency": limits["concurrent_calls"],
            "max_calls_per_second": limits["calls_per_second"],
            "max_duration_seconds": limits["call_duration_seconds"],
        },
        "capture": {"interface": "any", "output": "work/call.pcap"},
        "features": {
            "ice": False,
            "turn": False,
            "srtp": any(item in protection for item in ("sdes-srtp", "dtls-srtp")),
            "dtls_srtp": "dtls-srtp" in protection,
            "webrtc": False,
        },
    }


def _profile_media(doc: dict[str, Any]) -> dict[str, Any] | None:
    """The owner's media answers become the profile's ``media`` section.

    ``codecs``: the expected codecs become the approved codecs; calls then
    offer only these and refuse any other. ``networks``: every media CIDR
    wider than one address (single addresses are already literal approved
    addresses); the guided call, the matrix, and srtp-policy admit a media
    peer inside them, for media only. ``port_range``: the far end's RTP
    ports; a negotiated media port outside it stops the call. Omitted when
    the scope names none of these, so such profiles are unchanged.
    """
    from sippycup_softphone.driver import SoftphoneError, canonical_codec

    media = doc.get("media") or {}
    section: dict[str, Any] = {}
    codecs = media.get("codecs")
    if isinstance(codecs, list) and codecs:
        names: list[str] = []
        for item in codecs:
            try:
                name = canonical_codec(item)
            except SoftphoneError:
                names = []
                break
            if name not in names:
                names.append(name)
        if names:
            section["codecs"] = names
    networks: list[str] = []
    addresses: list[str] = []
    for text in media.get("networks") or []:
        try:
            network = canonical_network(str(text).strip())
        except ValueError:
            continue
        if network.prefixlen != network.max_prefixlen and str(network) not in networks:
            networks.append(str(network))
        elif network.prefixlen == network.max_prefixlen and str(network.network_address) not in addresses:
            addresses.append(str(network.network_address))
    if isinstance(media.get("networks"), list) and media["networks"]:
        # The owner's media answer (question 12) promises media only there:
        # the single addresses it lists, possibly none (ranges only). A call
        # admits media at no other literal approved address, not even the
        # signaling address (media_scope.media_addresses).
        section["addresses"] = addresses
    if networks:
        section["networks"] = networks
    port_range = media.get("port_range")
    if (
        isinstance(port_range, dict)
        and type(port_range.get("start")) is int
        and type(port_range.get("end")) is int
        and 1 <= port_range["start"] <= port_range["end"] <= 65535
    ):
        section["port_range"] = {"start": port_range["start"], "end": port_range["end"]}
    return section or None


def _compile_profiles(
    doc: dict[str, Any], report: Report, instant: datetime
) -> tuple[list[tuple[str, bytes]], dict[str, str], str | None]:
    """Build one validated profile per target.

    Returns ``([(sidecar key, bytes)], {sidecar key: why it was not written},
    authorization status)``. Every profile carries its own target (transport,
    port, TLS name and CA), the destinations approved for that target, and the
    same approval, window, addresses, limits, and media scope. The
    ``security_checks`` section belongs to the first target only.
    """
    from sippycup_checks.scope_support import profile_section

    built: list[tuple[str, bytes]] = []
    problems: dict[str, str] = {}
    status: str | None = None
    security_checks = profile_section(doc)
    media_section = _profile_media(doc)
    for index, target in enumerate(normalized_targets(doc)):
        key = profile_key(target["name"] if index else None)
        profile = _build_profile(doc, report, index)
        if index == 0 and security_checks is not None:
            profile["security_checks"] = security_checks
        if media_section is not None:
            profile["media"] = media_section
        status = status or profile["authorization"]["status"]
        data = _dump(profile)
        problem = _validate_profile(data, profile["authorization"]["status"] == "approved", instant)
        if problem:
            problems[key] = problem
        else:
            built.append((key, data))
    return built, problems, status


def _campaign_networks(doc: dict[str, Any]) -> tuple[list[str], list[str]]:
    """``(networks, mediaNetworks)`` for the campaign manifest.

    Signaling networks become ``authorization.networks`` (signaling targets
    and media). Media networks that no signaling network already contains
    become the media-only ``authorization.mediaNetworks``, so a media server
    pool never becomes an acceptable signaling destination in the planner.
    When they do not meet the media breadth rule (more than 16 networks or
    1024 addresses; ``scope check`` flags that), they are merged into
    ``networks`` as before so the campaign still compiles.
    """
    from .media_scope import validate_networks

    signaling = {canonical_network(text) for text in doc["signaling"]["networks"]}
    media: list[Any] = []
    for text in doc["media"]["networks"]:
        network = canonical_network(text)
        if network in media or any(
            network.version == item.version and network.subnet_of(item) for item in signaling
        ):
            continue
        media.append(network)

    def ordered(items: Any) -> list[str]:
        return [
            str(item)
            for item in sorted(items, key=lambda n: (n.version, int(n.network_address), n.prefixlen))
        ]

    if media and validate_networks(ordered(media), []) is None:
        return sorted({str(item) for item in signaling | set(media)}), []
    return sorted({str(item) for item in signaling}), ordered(media)


def _build_campaign(doc: dict[str, Any]) -> dict[str, Any] | list[tuple[str, str]]:
    limits = doc["limits"]
    targets = normalized_targets(doc)
    destinations = normalized_destinations(doc)
    budget = baseline_budget(
        limits,
        doc["test_scope"]["allowed_classes"],
        targets,
        destinations,
        pps=limits["packets_per_second"],
    )
    if isinstance(budget, list):
        return budget
    networks, media_networks = _campaign_networks(doc)
    account = doc["account"]
    credential = account.get("credential_ref") if account.get("required") else None
    stops = doc["stop_conditions"]
    media = doc["media"]["port_range"]
    manifest_targets = []
    for item in targets:
        signaling: dict[str, Any] = {"transport": item["transport"], "port": item["port"]}
        if item["transport"] == "tls":
            if item.get("tls_server_name"):
                signaling["tlsServerName"] = item["tls_server_name"]
            if item.get("tls_ca_file"):
                signaling["tlsCaFile"] = item["tls_ca_file"]
        entry: dict[str, Any] = {
            "name": item["name"],
            "address": item["address"],
            "signaling": signaling,
        }
        if credential:
            entry["credentialRef"] = credential
            # A required account registers first, like the guided call; the
            # softphone runner dials only after registration succeeds.
            manifest_account: dict[str, Any] = {"username": account["username"]}
            if account.get("realm"):
                manifest_account["realm"] = account["realm"]
            manifest_account["register"] = True
            entry["account"] = manifest_account
        manifest_targets.append(entry)
    cases: list[dict[str, Any]] = []
    by_target: dict[str, list[str]] = {}
    dial_user: dict[str, str] = {}
    for item in destinations:
        by_target.setdefault(item["target"], []).append(item["expect"])
        if item["expect"] != "reject":
            dial_user.setdefault(item["target"], item["user"])
    for item in targets:
        if budget["options"] is not None:
            cases.append(
                {
                    "id": f"{item['name']}-options",
                    "type": "options",
                    "target": item["name"],
                    "count": 1,
                    "budget": {
                        "packetsPerRun": budget["options"]["packets"],
                        "bytesPerRun": budget["options"]["bytes"],
                        "durationSecondsPerRun": budget["options"]["seconds"],
                    },
                    "expectations": {
                        "apiVersion": "sippycup.dev/case-expectations/v1",
                        "finalStatus": 200,
                    },
                }
            )
        if item["name"] in budget["call_targets"]:
            behaviors = by_target[item["name"]]
            expectations: dict[str, Any] = {"apiVersion": "sippycup.dev/case-expectations/v1"}
            if all(behavior != "reject" for behavior in behaviors):
                expectations["finalStatus"] = 200
                expectations["requireBidirectionalRtp"] = True
            call_case: dict[str, Any] = {
                "id": f"{item['name']}-call",
                "type": "call",
                "target": item["name"],
                "count": 1,
            }
            if item["name"] in dial_user:
                call_case["dial"] = {"user": dial_user[item["name"]]}
            call_case["budget"] = {
                "packetsPerRun": budget["call"]["packets"],
                "bytesPerRun": budget["call"]["bytes"],
                "durationSecondsPerRun": budget["call"]["seconds"],
            }
            call_case["expectations"] = expectations
            cases.append(call_case)
    authorization: dict[str, Any] = {"networks": networks}
    if media_networks:
        authorization["mediaNetworks"] = media_networks
    # The owner's media answer (question 12): media goes only there, so a
    # call step admits media at its own signaling address only when the
    # owner listed it for media too (campaign.py, mediaAllowed).
    authorization["mediaAllowed"] = sorted(
        {str(canonical_network(str(text).strip())) for text in doc["media"]["networks"]},
        key=lambda text: (ipaddress.ip_network(text).version, int(ipaddress.ip_network(text).network_address),
                          ipaddress.ip_network(text).prefixlen),
    )
    # The approval window (bn-3vxl): campaign plan freezes it and campaign run
    # sends nothing outside it. The manifest is generated only for an approved
    # scope with a complete window, so these answers exist.
    auth = doc.get("authorization") or {}
    try:
        valid_from, valid_until = canonical_window(
            auth.get("valid_from"), auth.get("valid_until"), "authorization"
        )
    except ApprovalError as exc:
        return [("authorization.valid_until", str(exc))]
    approval: dict[str, Any] = {}
    if isinstance(auth.get("approval_id"), str) and auth["approval_id"].strip():
        approval["id"] = auth["approval_id"].strip()
    if valid_from is not None:
        approval["validFrom"] = valid_from
    approval["validUntil"] = valid_until
    authorization["approval"] = approval
    authorization |= {
        "signalingPorts": list(doc["signaling"]["ports"]),
        "mediaPorts": {"start": media["start"], "end": media["end"]},
        "transports": list(doc["signaling"]["transports"]),
    }
    if credential:
        authorization["credentialRefs"] = [credential]
    authorization["ceilings"] = {
        "calls": limits["calls"],
        "packets": limits["packets"],
        "bytes": limits["bytes"],
        "durationSeconds": limits["total_duration_seconds"],
        "concurrentCalls": limits["concurrent_calls"],
        "packetsPerSecond": limits["packets_per_second"],
        "callsPerSecond": limits["calls_per_second"],
    }
    authorization["stopConditions"] = {
        "consecutiveFailures": stops["consecutive_failures"],
        "unexpectedResponse": stops["unexpected_response"],
        "packetLossPercent": stops["packet_loss_percent"],
    }
    return {
        "apiVersion": "sippycup.dev/v1",
        "kind": "Campaign",
        "metadata": {"name": doc["name"]},
        "authorization": authorization,
        "targets": manifest_targets,
        "cases": cases,
        "expectations": {
            "allowedSipStatuses": [100, 180, 200],
            "requireBidirectionalRtp": any(
                item["expect"] != "reject" for item in destinations
            ),
        },
        "evidence": {
            "capture": True,
            "retainPayload": False,
            "directory": f"evidence/{doc['name']}",
        },
    }


def _build_expectations(doc: dict[str, Any]) -> dict[str, Any]:
    endpoints: list[str] = []

    def add(value: str) -> None:
        if value not in endpoints:
            endpoints.append(value)

    for item in normalized_targets(doc):
        add(item["address"])
    for text in doc["media"]["networks"]:
        network = canonical_network(text)
        if network.prefixlen == network.max_prefixlen:
            add(str(network.network_address))
        else:
            for address in network:
                add(str(address))
    for text in doc["client"]["source_addresses"]:
        add(str(ipaddress.ip_address(text)))
    destinations = normalized_destinations(doc)
    parameters: dict[str, Any] = {
        "require_bidirectional": any(item["expect"] != "reject" for item in destinations),
        "expected_codecs": [item.strip().upper() for item in doc["media"]["codecs"]],
        # The DTMF answer names the method the service supports. A baseline
        # call sends no digits, so requiring DTMF here would fail every
        # ordinary capture; a digit-sending test must opt in explicitly.
        "require_dtmf": False,
        "allow_symmetric_rtp": doc["media"]["symmetric_rtp"],
    }
    return {
        "schema_version": "sippycup.expectations/v1",
        "capture": {"allowed_endpoints": endpoints},
        "expectations": [
            {
                "id": "authorized-call-path",
                "type": "call_path",
                "on_unknown": "inconclusive",
                "parameters": parameters,
            }
        ],
    }


def _fail_resolver(host: str) -> list[str]:  # pragma: no cover - literal targets only
    raise ManifestError(f"refusing DNS lookup for {host}")


def _validate_profile(data: bytes, approved: bool, now: datetime) -> str | None:
    document = yaml.safe_load(data.decode())
    result = rehearse(document, now=now)
    if approved:
        return None if result.ready else "; ".join(result.errors)
    allowed = ("authorization", "approved_by", "approved profiles", "at least one literal approved")
    stray = [error for error in result.errors if not error.startswith(allowed)]
    return "; ".join(stray) if stray else None


def _validate_campaign(data: bytes) -> str | None:
    try:
        compile_plan(yaml.safe_load(data.decode()), _sha256(data), resolver=_fail_resolver)
    except ManifestError as exc:
        return str(exc)
    return None


def _validate_expectations(data: bytes) -> str | None:
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "expectations.yaml"
        path.write_bytes(data)
        try:
            load_expectations(path)
        except ExpectationsError as exc:
            return str(exc)
    return None


def read_sidecar(directory: Path) -> tuple[dict[str, Any] | None, str | None]:
    path = directory / SIDECAR_FILE
    if not path.exists() and not path.is_symlink():
        return None, None
    try:
        if path.is_symlink() or not path.is_file() or path.stat().st_size > 1024 * 1024:
            raise ValueError("not a regular file within the size limit")
        value = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(value, dict) or value.get("schema_version") != SIDECAR_VERSION:
            raise ValueError("unsupported schema_version")
        derivatives = value.get("derivatives")
        if not isinstance(derivatives, dict):
            raise ValueError("derivatives must be an object")
        for name, entry in derivatives.items():
            extra = _key_target(name) if isinstance(name, str) else None
            if (name not in FILENAMES and name not in RECORD_ONLY and extra is None) or not isinstance(entry, dict) or not all(
                isinstance(entry.get(key), str) for key in ("path", "sha256", "scopeSha256")
            ):
                raise ValueError("malformed derivative entry")
            if name in RECORD_ONLY and entry["path"] != RECORD_ONLY[name]:
                raise ValueError("malformed derivative entry")
            # A further target's profile lives only at its predictable name
            # (compile removes it when the target leaves the scope).
            if extra is not None and entry["path"] != profile_filename(extra):
                raise ValueError("malformed derivative entry")
        return value, None
    except (OSError, ValueError) as exc:
        return None, f"cannot trust {SIDECAR_FILE}: {exc}"


def _write_atomic(path: Path, data: bytes, *, replace: bool) -> None:
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(temporary, 0o600)
        if replace:
            os.replace(temporary, path)
        else:
            os.link(temporary, path)
        path.chmod(0o600)
    finally:
        temporary.unlink(missing_ok=True)


def compile_scope(
    engagement: str | Path,
    *,
    scope: str | Path | None = None,
    force: bool = False,
    now: datetime | None = None,
) -> CompileResult:
    root = Path(engagement)
    instant = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
    report = inspect(scope_path_for(root, scope), now=instant)
    result = CompileResult(report)
    if report.fatal or report.document is None:
        return result
    doc = report.document
    if not root.is_dir() or root.is_symlink():
        result.refused.append(
            Finding("scope.unsafe_path", "error", "invalid", str(root), "engagement directory is missing or a symlink")
        )
        return result

    builders: dict[str, bytes] = {}
    # Sidecar key -> file name; a further target's profile adds its own key.
    filenames: dict[str, str] = dict(FILENAMES)
    result.profile_status = None
    profiles_built = False
    for artifact in ARTIFACTS:
        reasons = report.blocked(artifact)
        if reasons:
            result.skipped[artifact] = reasons
            continue
        problem: str | None
        if artifact == PROFILE:
            profiles_built = True
            built, problems, result.profile_status = _compile_profiles(doc, report, instant)
            result.expected = len(ARTIFACTS) - 1 + len(built) + len(problems)
            for key, data in built:
                builders[key] = data
                filenames[key] = profile_filename(_key_target(key))
            for key, why in problems.items():
                result.skipped[key] = [
                    Finding(
                        "scope.derivative_invalid",
                        "error",
                        "invalid",
                        key,
                        f"generated {profile_filename(_key_target(key))} failed its validator "
                        f"and was not written: {why}",
                    )
                ]
            continue
        elif artifact == CAMPAIGN:
            manifest = _build_campaign(doc)
            if isinstance(manifest, list):
                data, problem = b"", "; ".join(message for _, message in manifest)
            else:
                data = _dump(manifest)
                problem = _validate_campaign(data)
        else:
            data = _dump(_build_expectations(doc))
            problem = _validate_expectations(data)
        if problem:
            result.skipped[artifact] = [
                Finding(
                    "scope.derivative_invalid",
                    "error",
                    "invalid",
                    artifact,
                    f"generated {artifact} failed its validator and was not written: {problem}",
                )
            ]
            continue
        builders[artifact] = data

    sidecar, sidecar_problem = read_sidecar(root)
    recorded = (sidecar or {}).get("derivatives", {})
    for artifact in builders:
        path = root / filenames[artifact]
        if path.is_symlink():
            result.refused.append(
                Finding("scope.unsafe_path", "error", "invalid", filenames[artifact], "derivative path is a symlink")
            )
            continue
        if not path.exists() or force:
            continue
        entry = recorded.get(artifact)
        if entry is None or entry["path"] != filenames[artifact]:
            code, why = (
                "scope.derivative_unmanaged",
                "exists but was not generated by scope compile",
            )
        elif _sha256(path.read_bytes()) != entry["sha256"]:
            code, why = (
                "scope.derivative_modified",
                "was edited after it was generated",
            )
        else:
            continue
        result.refused.append(
            Finding(code, "error", "inconsistent", filenames[artifact], f"{filenames[artifact]} {why}; "
                    "re-run with --force to overwrite it")
        )
    from . import scope_app_derive

    app_data, app_skips, app_refusals = scope_app_derive.precheck(root, report, force)
    if app_skips:
        result.skipped[scope_app_derive.ARTIFACT] = app_skips
    result.refused.extend(app_refusals)
    if sidecar_problem:
        result.notes.append(sidecar_problem)
    if result.refused:
        result.profile_status = None
        return result

    generated_at = instant.isoformat()
    derivatives = {
        name: dict(entry)
        for name, entry in recorded.items()
        if name not in builders and (root / entry["path"]).exists()
    }
    if profiles_built:
        # A target that left the scope must not keep an approved profile: its
        # unedited file is removed; an edited one is left for the operator.
        remaining = {item["name"] for item in doc["targets"][1:]}
        for name in sorted(derivatives):
            target_name = _key_target(name)
            if target_name is None or target_name in remaining:
                continue
            entry = derivatives.pop(name)
            obsolete = root / profile_filename(target_name)
            if obsolete.is_symlink() or not obsolete.is_file():
                continue
            if _sha256(obsolete.read_bytes()) == entry["sha256"]:
                obsolete.unlink()
                result.removed.append(obsolete.name)
                result.notes.append(
                    f"removed {obsolete.name}: target {target_name} is no longer a further target in the scope"
                )
            else:
                result.notes.append(
                    f"{obsolete.name} belongs to target {target_name}, which is no longer a further "
                    "target in the scope, and was edited by hand, so it was left in place and is no "
                    "longer tracked: do not use it; delete it yourself"
                )
    for artifact, data in builders.items():
        path = root / filenames[artifact]
        _write_atomic(path, data, replace=path.exists())
        digest = _sha256(data)
        derivatives[artifact] = {
            "path": filenames[artifact],
            "sha256": digest,
            "scopeSha256": report.sha256,
        }
        generated = {"artifact": artifact, "path": str(path), "sha256": digest}
        if artifact == PROFILE or _key_target(artifact) is not None:
            generated["target"] = (
                doc["targets"][0]["name"] if artifact == PROFILE else _key_target(artifact)
            )
            derivatives[artifact]["target"] = generated["target"]
        result.generated.append(generated)
    # The application record is written by compile too: write it before the
    # sidecar and record its hash there, like every other file compile wrote.
    result.application, app_notes = scope_app_derive.finish(root, report, app_data, _write_atomic)
    if app_data is not None:
        derivatives[scope_app_derive.ARTIFACT] = {
            "path": scope_app_derive.FILENAME,
            "sha256": _sha256(app_data),
            "scopeSha256": report.sha256,
        }
    scope_file = Path(report.path)
    try:
        recorded_path = str(scope_file.resolve().relative_to(root.resolve()))
    except ValueError:
        recorded_path = str(scope_file)
    sidecar_value = {
        "schema_version": SIDECAR_VERSION,
        "scope": {"path": recorded_path, "sha256": report.sha256},
        "generated_at": generated_at,
        "derivatives": dict(sorted(derivatives.items())),
        "skipped": {
            name: sorted({item.code for item in items})
            for name, items in sorted(result.skipped.items())
        },
    }
    sidecar_path = root / SIDECAR_FILE
    _write_atomic(
        sidecar_path,
        (json.dumps(sidecar_value, indent=2, sort_keys=True) + "\n").encode(),
        replace=sidecar_path.exists(),
    )
    result.generated_at = generated_at
    result.notes.extend(app_notes)
    targets_raw = [item for item in doc.get("targets") or [] if isinstance(item, dict)]
    by_name = {item["name"]: item for item in targets_raw if "name" in item}
    written_profiles = [
        f"{Path(item['path']).name} ({item['target']}, {by_name[item['target']]['transport']} "
        f"port {by_name[item['target']]['port']})"
        for item in result.generated
        if "target" in item
    ]
    if len(targets_raw) > 1 and written_profiles:
        result.notes.append(
            "one target profile per target: " + "; ".join(written_profiles) + ". Pass the profile "
            "of the target you are testing to rehearse, call, and matrix; each approves only the "
            "destinations the scope lists for its target"
        )
    if EXPECTATIONS in builders and any(
        item["expect"] == "reject" for item in normalized_destinations(doc)
    ):
        result.notes.append(
            "a destination expected to reject has no generated final-status expectation"
        )
    if PROFILE in builders:
        written = yaml.safe_load(builders[PROFILE].decode()).get("media") or {}
        if written.get("networks"):
            from .media_scope import describe

            result.notes.append(
                f"media networks {describe(written['networks'])} are in the profile's media.networks: "
                "the guided call, the call matrix, and srtp-policy accept a media peer inside them "
                "(media only; signaling still goes only to the literal target.host)"
            )
        if written.get("port_range"):
            ports = written["port_range"]
            result.notes.append(
                f"media port range {ports['start']}-{ports['end']} is in the profile's media.port_range: "
                "a call stops when the far end negotiates a media port outside it"
            )
    return result


def operator_path(path: str | Path) -> str:
    """A path as the operator types it on the host (``work/...``), also inside the image."""
    text = str(path)
    if text.startswith("/work/"):
        return "work/" + text[len("/work/"):]
    parts = Path(text).parts
    if "work" in parts:
        index = len(parts) - 1 - parts[::-1].index("work")
        return str(Path(*parts[index:]))
    return text


# Write-once copies of each scope file a sender ran under, named by SHA-256
# (bn-2rgk): summary judges each run by the scope in force when it ran.
APPROVED_SCOPES_DIR = "approved-scopes"


def archive_scope(directory: str | Path, scope_sha256: str) -> str | None:
    """Keep a write-once copy of the scope file whose SHA-256 a run recorded.

    Returns its path relative to the engagement directory, or None when the
    scope file no longer has that hash or the copy cannot be written (the run
    is then judged against the current records). Never blocks a send.
    """
    directory = Path(directory)
    sidecar, _problem = read_sidecar(directory)
    recorded = ((sidecar or {}).get("scope") or {}).get("path")
    name = recorded if isinstance(recorded, str) and recorded and "/" not in recorded else "scope.yaml"
    source = directory / name
    try:
        if source.is_symlink() or not source.is_file():
            return None
        data = source.read_bytes()
        if _sha256(data) != scope_sha256:
            return None
        archive = directory / APPROVED_SCOPES_DIR
        if archive.is_symlink():
            return None
        archive.mkdir(mode=0o700, exist_ok=True)
        target = archive / f"scope-{scope_sha256}.yaml"
        relative = f"{APPROVED_SCOPES_DIR}/{target.name}"
        try:
            descriptor = os.open(
                target, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600
            )
        except FileExistsError:
            if not target.is_symlink() and target.is_file() and _sha256(target.read_bytes()) == scope_sha256:
                return relative
            return None
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        return relative
    except OSError:
        return None


def approval_record(path: str | Path, content: bytes | None = None) -> dict[str, Any]:
    """What a run records about the approval in force when it sent (bn-2rgk)."""
    found = derivative_integrity(path, content)
    record = {
        "state": found["state"],
        "source": Path(path).name,
        "sha256": found["sha256"],
        "scopeSha256": found["scopeSha256"],
        "scopeArchive": None,
    }
    if found["state"] == "compiled-current" and found["scopeSha256"]:
        record["scopeArchive"] = archive_scope(Path(path).parent, found["scopeSha256"])
    return record


def derivative_integrity(path: str | Path, content: bytes | None = None) -> dict[str, Any]:
    """Is this the file ``scope compile`` wrote, unchanged, from the current scope? (bn-zqe8)

    The send-time form of the check that ``ready`` and ``scope compile`` make,
    for a target profile or a campaign manifest about to be used for traffic.
    ``content`` is the exact bytes the caller will use (read from ``path``
    when omitted). Returns ``state``:

    - ``compiled-current``: recorded in ``scope-derivatives.json`` beside it,
      byte for byte as written, and the scope file is unchanged since;
    - ``not-compiled``: no record beside it and no compile header (a profile
      written by hand, the practice target's, or a self-test's): nothing ties
      it to a scope file, as before;

    and for every other state an ``error`` that says what is wrong and the
    exact command that recovers. Reads only local files; sends nothing.
    """
    target = Path(path)
    shown = operator_path(target)
    engagement = operator_path(target.parent)
    value: dict[str, Any] = {"state": None, "path": target.name, "sha256": None, "scopeSha256": None, "error": None}

    def refuse(state: str, why: str, fix: str) -> dict[str, Any]:
        value["state"] = state
        value["error"] = (
            f"{shown} {why}; nothing was sent. Never edit a compiled profile or manifest: "
            f"{fix}"
        )
        return value

    if content is None:
        try:
            content = target.read_bytes()
        except OSError as exc:
            return refuse("unreadable", f"cannot be read ({exc.strerror or exc})",
                          f"run ./bin/sippycup scope compile {engagement}")
    value["sha256"] = _sha256(content)
    generated = content.startswith(HEADER.encode())
    sidecar, problem = read_sidecar(target.parent)
    if problem:
        return refuse(
            "record-unreadable",
            f"cannot be checked against what scope compile wrote ({problem})",
            f"run ./bin/sippycup scope compile --force {engagement} to write the profiles and "
            "their record again from scope.yaml",
        )
    if sidecar is None:
        if generated:
            return refuse(
                "unrecorded",
                f"carries the scope compile header, but there is no {SIDECAR_FILE} beside it "
                "(it was copied from another directory, or the record was removed)",
                "use the profile in the engagement directory where scope compile wrote it, or run "
                f"./bin/sippycup scope compile --force {engagement} there",
            )
        value["state"] = "not-compiled"
        return value
    entry = next(
        (item for item in sidecar["derivatives"].values() if item.get("path") == target.name),
        None,
    )
    if entry is None:
        return refuse(
            "unrecorded",
            f"was not written by scope compile, but it sits in an engagement directory whose "
            f"profiles and manifest scope compile manages ({SIDECAR_FILE} does not list it)",
            "use a profile that scope compile wrote (target-profile.yaml or "
            f"target-profile-NAME.yaml); to change what is approved, put it in {engagement}/scope.yaml "
            f"and run ./bin/sippycup scope compile {engagement}",
        )
    if value["sha256"] != entry["sha256"]:
        return refuse(
            "edited",
            "was edited after scope compile wrote it (its SHA-256 no longer matches "
            f"{SIDECAR_FILE})",
            f"put any change the owner approved in {engagement}/scope.yaml, then run "
            f"./bin/sippycup scope compile --force {engagement} to replace the edited file",
        )
    recorded_scope = (sidecar.get("scope") or {}).get("path")
    scope_file = target.parent / (recorded_scope if isinstance(recorded_scope, str) and recorded_scope
                                  and not Path(recorded_scope).is_absolute() else "scope.yaml")
    current = (
        _sha256(scope_file.read_bytes())
        if scope_file.is_file() and not scope_file.is_symlink()
        else None
    )
    value["scopeSha256"] = current
    if current is None:
        return refuse(
            "scope-missing",
            f"was compiled from {scope_file.name}, which is no longer in {engagement}",
            f"restore {engagement}/{scope_file.name} with the owner's answers and run "
            f"./bin/sippycup scope compile {engagement}",
        )
    if current != entry["scopeSha256"] and (sidecar.get("scope") or {}).get("sha256") == current:
        # scope compile ran on this scope and did not write this file again (a
        # pending approval, or another scope error): "run scope compile" alone
        # would send the operator round in a circle (rehearsal 3, finding 14).
        return refuse(
            "stale",
            f"no longer matches {engagement}/{scope_file.name}: the last scope compile did not write it again, "
            "because the scope is not approved or has an error, so this file is from an earlier scope",
            f"run ./bin/sippycup scope check {engagement} and fix what it reports (a pending approval is "
            f"recorded with ./bin/sippycup scope answer {engagement} 2), then run "
            f"./bin/sippycup scope compile {engagement}",
        )
    if current != entry["scopeSha256"]:
        return refuse(
            "stale",
            f"no longer matches {engagement}/{scope_file.name}, which changed after the last scope compile",
            f"run ./bin/sippycup scope compile {engagement}",
        )
    value["state"] = "compiled-current"
    return value


def integrity_error(path: str | Path, content: bytes | None = None) -> str | None:
    """The refusal for a profile or manifest that must not be used for traffic, else None."""
    return derivative_integrity(path, content)["error"]


def derivative_state(
    engagement: str | Path, scope: str | Path | None = None
) -> dict[str, Any]:
    """Describe whether derivatives are current. Reads only local files."""
    root = Path(engagement)
    scope_file = scope_path_for(root, scope)
    sidecar, problem = read_sidecar(root)
    current = (
        _sha256(scope_file.read_bytes())
        if scope_file.is_file() and not scope_file.is_symlink()
        else None
    )
    value: dict[str, Any] = {
        "sidecar": SIDECAR_FILE,
        "scopeSha256": current,
        "items": {},
        "skipped": {},
    }
    if problem:
        value["state"] = "invalid"
        value["problem"] = problem
        return value
    if sidecar is None:
        value["state"] = "not-compiled"
        return value
    value["skipped"] = sidecar.get("skipped", {})
    stale = False
    # The first target's profile, then the further targets', then the rest.
    ordered = sorted(
        sidecar["derivatives"].items(),
        key=lambda pair: (0 if pair[0] == PROFILE else 1 if _key_target(pair[0]) else 2, pair[0]),
    )
    for name, entry in ordered:
        if name in RECORD_ONLY:
            continue
        path = root / entry["path"]
        if not path.is_file() or path.is_symlink():
            state, edited, changed = "missing", False, False
        else:
            edited = _sha256(path.read_bytes()) != entry["sha256"]
            changed = entry["scopeSha256"] != current
            state = "edited" if edited else "stale" if changed else "current"
        value["items"][name] = {
            "path": entry["path"],
            "state": state,
            "scopeChanged": changed,
            "edited": edited,
        }
        if isinstance(entry.get("target"), str):
            value["items"][name]["target"] = entry["target"]
        stale = stale or state != "current"
    if (sidecar.get("scope") or {}).get("sha256") != current:
        stale = True
    if stale:
        value["state"] = "stale"
    elif value["skipped"]:
        value["state"] = "partial"
    else:
        value["state"] = "current"
    return value


def compiled_profiles(
    engagement: str | Path, scope: str | Path | None = None
) -> list[dict[str, Any]]:
    """Every target profile `scope compile` recorded, the first target's first.

    Each item: ``key`` (sidecar key), ``target`` (the scope target name, or
    ``None`` when an older sidecar did not record it), ``path`` (file name in
    the engagement directory), ``state`` (current, stale, edited, missing),
    and ``first``. Empty when nothing was compiled. Reads only local files.
    """
    try:
        state = derivative_state(engagement, scope)
    except (OSError, ValueError, KeyError, TypeError):
        return []
    result = []
    for name, item in (state.get("items") or {}).items():
        if name != PROFILE and _key_target(name) is None:
            continue
        result.append(
            {
                "key": name,
                "target": item.get("target") or _key_target(name),
                "path": item["path"],
                "state": item["state"],
                "first": name == PROFILE,
            }
        )
    return result
