"""Compile the scope file into derivatives and track their staleness.

Staleness model: ``scope-derivatives.json`` is a sidecar written next to the
derivatives. It records the scope file's SHA-256, and for every derivative its
path, its own SHA-256, and the scope hash it was generated from. The profile
and the campaign manifest reject unknown fields and the oracle loader rejects
unknown top-level keys, so no hash is embedded in the derivatives themselves.
The sidecar is an integrity aid for honest mistakes, not a tamper-proof seal.
"""

from __future__ import annotations

import hashlib
import ipaddress
import json
import os
import tempfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from sippycup.campaign import ManifestError, compile_plan
from sippycup_oracle.cli import ExpectationsError, load_expectations

from . import PROFILE_VERSION
from .profile import ProfileError, _parse_time, rehearse
from .scope import (
    ARTIFACTS,
    CAMPAIGN,
    EXPECTATIONS,
    PROFILE,
    Finding,
    Report,
    baseline_budget,
    canonical_network,
    inspect,
    normalized_destinations,
    normalized_targets,
    scope_path_for,
)

SIDECAR_FILE = "scope-derivatives.json"
SIDECAR_VERSION = "sippycup.dev/scope-derivatives/v1"
COMPILE_VERSION = "sippycup.dev/scope-compile/v1"
FILENAMES = {
    PROFILE: "target-profile.yaml",
    CAMPAIGN: "campaign.yaml",
    EXPECTATIONS: "expectations.yaml",
}
HEADER = (
    "# Generated by `./bin/sippycup scope compile` from the private scope file.\n"
    "# Do not edit by hand: change the scope file and compile again. A hand edit is\n"
    "# reported as an edited derivative and blocks the next compile without --force.\n"
)


@dataclass
class CompileResult:
    report: Report
    generated: list[dict[str, str]] = field(default_factory=list)
    skipped: dict[str, list[Finding]] = field(default_factory=dict)
    refused: list[Finding] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    profile_status: str | None = None
    generated_at: str | None = None

    @property
    def exit_code(self) -> int:
        if self.report.fatal or self.refused:
            return 2
        if self.report.ok and len(self.generated) == len(ARTIFACTS):
            return 0
        return 1

    def as_dict(self) -> dict[str, Any]:
        return {
            "apiVersion": COMPILE_VERSION,
            "scope": {"path": self.report.path, "sha256": self.report.sha256},
            "ok": self.exit_code == 0,
            "profileStatus": self.profile_status,
            "generated": self.generated,
            "skipped": {
                name: [item.as_dict() for item in items]
                for name, items in sorted(self.skipped.items())
            },
            "refused": [item.as_dict() for item in self.refused],
            "invalidScope": [item.as_dict() for item in self.report.findings] if self.report.fatal else [],
            "notes": self.notes,
            "networkActivity": False,
        }


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _dump(document: dict[str, Any]) -> bytes:
    return (HEADER + yaml.safe_dump(document, sort_keys=False, default_flow_style=False)).encode()


def _iso(value: Any) -> str | None:
    if value is None:
        return None
    try:
        parsed = _parse_time(value, "time")
    except ProfileError:
        return None
    return parsed.isoformat() if parsed else None


def _build_profile(doc: dict[str, Any], report: Report) -> dict[str, Any]:
    auth = doc.get("authorization") or {}
    status = auth.get("status")
    if status == "approved" and not report.ok:
        status = "pending"
    targets = normalized_targets(doc)
    first = targets[0]
    addresses: list[str] = []
    for item in targets:
        if item["address"] not in addresses:
            addresses.append(item["address"])
    for text in (doc.get("media") or {}).get("networks") or []:
        try:
            network = canonical_network(text)
        except ValueError:
            continue
        if network.prefixlen == network.max_prefixlen:
            literal = str(network.network_address)
            if literal not in addresses:
                addresses.append(literal)
    protection = doc["media"]["protection"]
    approved_by = auth.get("approved_by")
    approval_id = auth.get("approval_id")
    limits = doc["limits"]
    profile_target: dict[str, Any] = {
        "host": first["address"],
        "port": first["port"],
        "transport": first["transport"],
    }
    if first["transport"] == "tls":
        # The reviewed certificate name and trust anchor; the profile still
        # connects only to the literal host.
        if first.get("tls_server_name"):
            profile_target["tls_server_name"] = first["tls_server_name"]
        if first.get("tls_ca_file"):
            profile_target["tls_ca_file"] = first["tls_ca_file"]
    profile_target["approved_addresses"] = addresses
    return {
        "schema_version": PROFILE_VERSION,
        "name": doc["name"],
        "target": profile_target,
        "authorization": {
            "status": status,
            "approved_by": approved_by if isinstance(approved_by, str) else "",
            "approval_id": approval_id if isinstance(approval_id, str) else "",
            "valid_from": _iso(auth.get("valid_from")),
            "valid_until": _iso(auth.get("valid_until")),
        },
        "limits": {
            "max_calls": limits["calls"],
            "max_concurrency": limits["concurrent_calls"],
            "max_calls_per_second": limits["calls_per_second"],
            "max_duration_seconds": limits["call_duration_seconds"],
        },
        "capture": {"interface": "any", "output": "work/call.pcap"},
        "features": {
            "ice": False,
            "turn": False,
            "srtp": any(item in protection for item in ("sdes-srtp", "dtls-srtp")),
            "dtls_srtp": "dtls-srtp" in protection,
            "webrtc": False,
        },
    }


def _build_campaign(doc: dict[str, Any]) -> dict[str, Any] | list[tuple[str, str]]:
    limits = doc["limits"]
    targets = normalized_targets(doc)
    destinations = normalized_destinations(doc)
    budget = baseline_budget(
        limits,
        doc["test_scope"]["allowed_classes"],
        targets,
        destinations,
        pps=limits["packets_per_second"],
    )
    if isinstance(budget, list):
        return budget
    networks = sorted(
        {
            str(canonical_network(text))
            for text in [*doc["signaling"]["networks"], *doc["media"]["networks"]]
        }
    )
    account = doc["account"]
    credential = account.get("credential_ref") if account.get("required") else None
    stops = doc["stop_conditions"]
    media = doc["media"]["port_range"]
    manifest_targets = []
    for item in targets:
        signaling: dict[str, Any] = {"transport": item["transport"], "port": item["port"]}
        if item["transport"] == "tls":
            if item.get("tls_server_name"):
                signaling["tlsServerName"] = item["tls_server_name"]
            if item.get("tls_ca_file"):
                signaling["tlsCaFile"] = item["tls_ca_file"]
        entry: dict[str, Any] = {
            "name": item["name"],
            "address": item["address"],
            "signaling": signaling,
        }
        if credential:
            entry["credentialRef"] = credential
            # A required account registers first, like the guided call; the
            # softphone runner dials only after registration succeeds.
            manifest_account: dict[str, Any] = {"username": account["username"]}
            if account.get("realm"):
                manifest_account["realm"] = account["realm"]
            manifest_account["register"] = True
            entry["account"] = manifest_account
        manifest_targets.append(entry)
    cases: list[dict[str, Any]] = []
    by_target: dict[str, list[str]] = {}
    dial_user: dict[str, str] = {}
    for item in destinations:
        by_target.setdefault(item["target"], []).append(item["expect"])
        if item["expect"] != "reject":
            dial_user.setdefault(item["target"], item["user"])
    for item in targets:
        if budget["options"] is not None:
            cases.append(
                {
                    "id": f"{item['name']}-options",
                    "type": "options",
                    "target": item["name"],
                    "count": 1,
                    "budget": {
                        "packetsPerRun": budget["options"]["packets"],
                        "bytesPerRun": budget["options"]["bytes"],
                        "durationSecondsPerRun": budget["options"]["seconds"],
                    },
                    "expectations": {
                        "apiVersion": "sippycup.dev/case-expectations/v1",
                        "finalStatus": 200,
                    },
                }
            )
        if item["name"] in budget["call_targets"]:
            behaviors = by_target[item["name"]]
            expectations: dict[str, Any] = {"apiVersion": "sippycup.dev/case-expectations/v1"}
            if all(behavior != "reject" for behavior in behaviors):
                expectations["finalStatus"] = 200
                expectations["requireBidirectionalRtp"] = True
            call_case: dict[str, Any] = {
                "id": f"{item['name']}-call",
                "type": "call",
                "target": item["name"],
                "count": 1,
            }
            if item["name"] in dial_user:
                call_case["dial"] = {"user": dial_user[item["name"]]}
            call_case["budget"] = {
                "packetsPerRun": budget["call"]["packets"],
                "bytesPerRun": budget["call"]["bytes"],
                "durationSecondsPerRun": budget["call"]["seconds"],
            }
            call_case["expectations"] = expectations
            cases.append(call_case)
    authorization: dict[str, Any] = {
        "networks": networks,
        "signalingPorts": list(doc["signaling"]["ports"]),
        "mediaPorts": {"start": media["start"], "end": media["end"]},
        "transports": list(doc["signaling"]["transports"]),
    }
    if credential:
        authorization["credentialRefs"] = [credential]
    authorization["ceilings"] = {
        "calls": limits["calls"],
        "packets": limits["packets"],
        "bytes": limits["bytes"],
        "durationSeconds": limits["total_duration_seconds"],
        "concurrentCalls": limits["concurrent_calls"],
        "packetsPerSecond": limits["packets_per_second"],
        "callsPerSecond": limits["calls_per_second"],
    }
    authorization["stopConditions"] = {
        "consecutiveFailures": stops["consecutive_failures"],
        "unexpectedResponse": stops["unexpected_response"],
        "packetLossPercent": stops["packet_loss_percent"],
    }
    return {
        "apiVersion": "sippycup.dev/v1",
        "kind": "Campaign",
        "metadata": {"name": doc["name"]},
        "authorization": authorization,
        "targets": manifest_targets,
        "cases": cases,
        "expectations": {
            "allowedSipStatuses": [100, 180, 200],
            "requireBidirectionalRtp": any(
                item["expect"] != "reject" for item in destinations
            ),
        },
        "evidence": {
            "capture": True,
            "retainPayload": False,
            "directory": f"evidence/{doc['name']}",
        },
    }


def _build_expectations(doc: dict[str, Any]) -> dict[str, Any]:
    endpoints: list[str] = []

    def add(value: str) -> None:
        if value not in endpoints:
            endpoints.append(value)

    for item in normalized_targets(doc):
        add(item["address"])
    for text in doc["media"]["networks"]:
        network = canonical_network(text)
        if network.prefixlen == network.max_prefixlen:
            add(str(network.network_address))
        else:
            for address in network:
                add(str(address))
    for text in doc["client"]["source_addresses"]:
        add(str(ipaddress.ip_address(text)))
    destinations = normalized_destinations(doc)
    parameters: dict[str, Any] = {
        "require_bidirectional": any(item["expect"] != "reject" for item in destinations),
        "expected_codecs": [item.strip().upper() for item in doc["media"]["codecs"]],
        # The DTMF answer names the method the service supports. A baseline
        # call sends no digits, so requiring DTMF here would fail every
        # ordinary capture; a digit-sending test must opt in explicitly.
        "require_dtmf": False,
        "allow_symmetric_rtp": doc["media"]["symmetric_rtp"],
    }
    return {
        "schema_version": "sippycup.expectations/v1",
        "capture": {"allowed_endpoints": endpoints},
        "expectations": [
            {
                "id": "authorized-call-path",
                "type": "call_path",
                "on_unknown": "inconclusive",
                "parameters": parameters,
            }
        ],
    }


def _fail_resolver(host: str) -> list[str]:  # pragma: no cover - literal targets only
    raise ManifestError(f"refusing DNS lookup for {host}")


def _validate_profile(data: bytes, approved: bool, now: datetime) -> str | None:
    document = yaml.safe_load(data.decode())
    result = rehearse(document, now=now)
    if approved:
        return None if result.ready else "; ".join(result.errors)
    allowed = ("authorization", "approved_by", "approved profiles", "at least one literal approved")
    stray = [error for error in result.errors if not error.startswith(allowed)]
    return "; ".join(stray) if stray else None


def _validate_campaign(data: bytes) -> str | None:
    try:
        compile_plan(yaml.safe_load(data.decode()), _sha256(data), resolver=_fail_resolver)
    except ManifestError as exc:
        return str(exc)
    return None


def _validate_expectations(data: bytes) -> str | None:
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "expectations.yaml"
        path.write_bytes(data)
        try:
            load_expectations(path)
        except ExpectationsError as exc:
            return str(exc)
    return None


def read_sidecar(directory: Path) -> tuple[dict[str, Any] | None, str | None]:
    path = directory / SIDECAR_FILE
    if not path.exists() and not path.is_symlink():
        return None, None
    try:
        if path.is_symlink() or not path.is_file() or path.stat().st_size > 1024 * 1024:
            raise ValueError("not a regular file within the size limit")
        value = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(value, dict) or value.get("schema_version") != SIDECAR_VERSION:
            raise ValueError("unsupported schema_version")
        derivatives = value.get("derivatives")
        if not isinstance(derivatives, dict):
            raise ValueError("derivatives must be an object")
        for name, entry in derivatives.items():
            if name not in FILENAMES or not isinstance(entry, dict) or not all(
                isinstance(entry.get(key), str) for key in ("path", "sha256", "scopeSha256")
            ):
                raise ValueError("malformed derivative entry")
        return value, None
    except (OSError, ValueError) as exc:
        return None, f"cannot trust {SIDECAR_FILE}: {exc}"


def _write_atomic(path: Path, data: bytes, *, replace: bool) -> None:
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(temporary, 0o600)
        if replace:
            os.replace(temporary, path)
        else:
            os.link(temporary, path)
        path.chmod(0o600)
    finally:
        temporary.unlink(missing_ok=True)


def compile_scope(
    engagement: str | Path,
    *,
    scope: str | Path | None = None,
    force: bool = False,
    now: datetime | None = None,
) -> CompileResult:
    root = Path(engagement)
    instant = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
    report = inspect(scope_path_for(root, scope), now=instant)
    result = CompileResult(report)
    if report.fatal or report.document is None:
        return result
    doc = report.document
    if not root.is_dir() or root.is_symlink():
        result.refused.append(
            Finding("scope.unsafe_path", "error", "invalid", str(root), "engagement directory is missing or a symlink")
        )
        return result

    builders: dict[str, bytes] = {}
    result.profile_status = None
    for artifact in ARTIFACTS:
        reasons = report.blocked(artifact)
        if reasons:
            result.skipped[artifact] = reasons
            continue
        problem: str | None
        if artifact == PROFILE:
            profile = _build_profile(doc, report)
            from sippycup_checks.scope_support import profile_section

            security_checks = profile_section(doc)
            if security_checks is not None:
                profile["security_checks"] = security_checks
            result.profile_status = profile["authorization"]["status"]
            data = _dump(profile)
            problem = _validate_profile(data, profile["authorization"]["status"] == "approved", instant)
        elif artifact == CAMPAIGN:
            manifest = _build_campaign(doc)
            if isinstance(manifest, list):
                data, problem = b"", "; ".join(message for _, message in manifest)
            else:
                data = _dump(manifest)
                problem = _validate_campaign(data)
        else:
            data = _dump(_build_expectations(doc))
            problem = _validate_expectations(data)
        if problem:
            result.skipped[artifact] = [
                Finding(
                    "scope.derivative_invalid",
                    "error",
                    "invalid",
                    artifact,
                    f"generated {artifact} failed its validator and was not written: {problem}",
                )
            ]
            continue
        builders[artifact] = data

    sidecar, sidecar_problem = read_sidecar(root)
    recorded = (sidecar or {}).get("derivatives", {})
    for artifact in builders:
        path = root / FILENAMES[artifact]
        if path.is_symlink():
            result.refused.append(
                Finding("scope.unsafe_path", "error", "invalid", FILENAMES[artifact], "derivative path is a symlink")
            )
            continue
        if not path.exists() or force:
            continue
        entry = recorded.get(artifact)
        if entry is None or entry["path"] != FILENAMES[artifact]:
            code, why = (
                "scope.derivative_unmanaged",
                "exists but was not generated by scope compile",
            )
        elif _sha256(path.read_bytes()) != entry["sha256"]:
            code, why = (
                "scope.derivative_modified",
                "was edited after it was generated",
            )
        else:
            continue
        result.refused.append(
            Finding(code, "error", "inconsistent", FILENAMES[artifact], f"{FILENAMES[artifact]} {why}; "
                    "re-run with --force to overwrite it")
        )
    if sidecar_problem:
        result.notes.append(sidecar_problem)
    if result.refused:
        result.profile_status = None
        return result

    generated_at = instant.isoformat()
    derivatives = {
        name: dict(entry)
        for name, entry in recorded.items()
        if name not in builders and (root / entry["path"]).exists()
    }
    for artifact, data in builders.items():
        path = root / FILENAMES[artifact]
        _write_atomic(path, data, replace=path.exists())
        digest = _sha256(data)
        derivatives[artifact] = {
            "path": FILENAMES[artifact],
            "sha256": digest,
            "scopeSha256": report.sha256,
        }
        result.generated.append({"artifact": artifact, "path": str(path), "sha256": digest})
    scope_file = Path(report.path)
    try:
        recorded_path = str(scope_file.resolve().relative_to(root.resolve()))
    except ValueError:
        recorded_path = str(scope_file)
    sidecar_value = {
        "schema_version": SIDECAR_VERSION,
        "scope": {"path": recorded_path, "sha256": report.sha256},
        "generated_at": generated_at,
        "derivatives": dict(sorted(derivatives.items())),
        "skipped": {
            name: sorted({item.code for item in items})
            for name, items in sorted(result.skipped.items())
        },
    }
    sidecar_path = root / SIDECAR_FILE
    _write_atomic(
        sidecar_path,
        (json.dumps(sidecar_value, indent=2, sort_keys=True) + "\n").encode(),
        replace=sidecar_path.exists(),
    )
    result.generated_at = generated_at
    if PROFILE in builders and len(doc["targets"]) > 1:
        result.notes.append(
            "the target profile carries only the first target; the campaign manifest carries all of them"
        )
    if EXPECTATIONS in builders and any(
        item["expect"] == "reject" for item in normalized_destinations(doc)
    ):
        result.notes.append(
            "a destination expected to reject has no generated final-status expectation"
        )
    media = doc["media"]["networks"]
    if PROFILE in builders and any(
        canonical_network(text).prefixlen != canonical_network(text).max_prefixlen for text in media
    ):
        result.notes.append(
            "media CIDRs are not listed in the profile's approved_addresses (literal addresses only); "
            "the guided call hangs up when media is negotiated to an address that is not listed, "
            "so ask the owner for the literal media addresses"
        )
    return result


def derivative_state(
    engagement: str | Path, scope: str | Path | None = None
) -> dict[str, Any]:
    """Describe whether derivatives are current. Reads only local files."""
    root = Path(engagement)
    scope_file = scope_path_for(root, scope)
    sidecar, problem = read_sidecar(root)
    current = (
        _sha256(scope_file.read_bytes())
        if scope_file.is_file() and not scope_file.is_symlink()
        else None
    )
    value: dict[str, Any] = {
        "sidecar": SIDECAR_FILE,
        "scopeSha256": current,
        "items": {},
        "skipped": {},
    }
    if problem:
        value["state"] = "invalid"
        value["problem"] = problem
        return value
    if sidecar is None:
        value["state"] = "not-compiled"
        return value
    value["skipped"] = sidecar.get("skipped", {})
    stale = False
    for name, entry in sidecar["derivatives"].items():
        path = root / entry["path"]
        if not path.is_file() or path.is_symlink():
            state, edited, changed = "missing", False, False
        else:
            edited = _sha256(path.read_bytes()) != entry["sha256"]
            changed = entry["scopeSha256"] != current
            state = "edited" if edited else "stale" if changed else "current"
        value["items"][name] = {
            "path": entry["path"],
            "state": state,
            "scopeChanged": changed,
            "edited": edited,
        }
        stale = stale or state != "current"
    if (sidecar.get("scope") or {}).get("sha256") != current:
        stale = True
    if stale:
        value["state"] = "stale"
    elif value["skipped"]:
        value["state"] = "partial"
    else:
        value["state"] = "current"
    return value
