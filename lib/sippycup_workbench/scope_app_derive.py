"""The reviewable ``application-surfaces.yaml`` record written by ``scope compile``.

The record states, for the platform and every web, API, and WebSocket surface
in the scope file, what the owner approved, what is still pending, and what is
out of scope. It is bound to the scope's approval reference and window.

It is a record for review, not an input to any sender: no live application
runner exists, and nothing in Sippycup sends HTTP or WebSocket traffic to
these surfaces. Every value in it is copied from the scope file; the builder
adds no path, method, header, or body.

It is not a ``sippycup.dev/web-security-profile/v1`` profile and is not
validated against that contract: a profile also needs an adapter, a check
list, hard ceilings, a window of at most 24 hours, and credential source
references, none of which the scope file records.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Callable

import yaml

from .scope import Finding, Report
from .scope_app import (
    ANSWERED,
    APPLICATION,
    COMPONENTS,
    INVENTORY_PROVIDED,
    THIRD_PARTIES,
    _is_none_list,
    _items,
    _section,
    has_sections,
    readiness_of,
    state_of,
)

ARTIFACT = APPLICATION
FILENAME = "application-surfaces.yaml"
VERSION = "sippycup.dev/application-surfaces/v1"
NOTICE = (
    "Record for review only. No live application runner exists: nothing in Sippycup sends HTTP "
    "or WebSocket traffic to these surfaces, and this file authorizes none. Every value is copied "
    "from the scope file; no path, method, header, or body was added."
)
CONTRACT_NOTE = (
    "Not a web-security profile and not validated against sippycup.dev/web-security-profile/v1: "
    "that contract also needs an adapter, a check list, hard ceilings, a window of at most 24 "
    "hours, and credential source references, which the scope file does not record."
)
HEADER = (
    "# Generated by `./bin/sippycup scope compile` from the private scope file.\n"
    "# Do not edit by hand: change the scope file and compile again.\n"
    "# RECORD ONLY: no Sippycup command sends web or API requests to these surfaces.\n"
)
_AUTH_CODES = {
    "scope.authorization_not_approved",
    "scope.window_not_started",
    "scope.window_expired",
    "scope.window_order",
}


def _answer(value: Any) -> Any:
    """The recorded answer, with every open answer spelled out as open."""
    state = state_of(value)
    if state != ANSWERED:
        return state
    if _is_none_list(value):
        return []
    return value


def _time(value: Any) -> str | None:
    if value is None:
        return None
    return value.isoformat() if hasattr(value, "isoformat") else str(value)


def _content_digest(document: dict[str, Any]) -> str:
    body = {key: value for key, value in document.items() if key != "contentSha256"}
    return hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def build(document: dict[str, Any], report: Report) -> dict[str, Any]:
    """Build the record. Call only when no error blocks the application artifact."""
    facts = readiness_of(document, report)
    auth = document.get("authorization") if isinstance(document.get("authorization"), dict) else {}
    auth_problems = [
        item.message for item in report.errors
        if item.code in _AUTH_CODES or (item.code == "scope.missing" and item.field.startswith("authorization."))
    ]
    platform = _section(document, "platform")
    application = _section(document, "application")
    components = _section(platform, "components")
    environment = _section(platform, "environment")
    third = _section(platform, "third_parties")
    dialing = _section(platform, "dialing")
    operations = _section(platform, "operations")
    by_field = {item["field"]: item for item in facts["surfaces"]}
    surfaces = []
    for index, item in enumerate(_items(application.get("surfaces"))):
        fact = by_field[f"application.surfaces[{index}]"]
        state, opened = fact["state"], list(fact["open"])
        if state == "ready":
            if auth_problems:
                state, opened = "pending", [f"authorization: {text}" for text in auth_problems]
            else:
                state = "approved"
        entry: dict[str, Any] = {"name": fact["name"], "kind": _answer(item.get("kind")), "state": state}
        if state != "out-of-scope":
            entry |= {
                "baseUrl": _answer(item.get("base_url")),
                "connectAddress": _answer(item.get("connect_address")),
                "connectPort": _answer(item.get("connect_port")),
                "tlsServerName": _answer(item.get("tls_server_name")),
                "tlsCa": _answer(item.get("tls_ca")),
            }
            if item.get("tls_ca_file") is not None:
                entry["tlsCaFile"] = item["tls_ca_file"]
            if item.get("kind") == "websocket" or item.get("allowed_origins") is not None:
                entry["allowedOrigins"] = _answer(item.get("allowed_origins"))
        entry["open"] = opened
        surfaces.append(entry)
    inventory = _section(application, "route_inventory")
    record: dict[str, Any] = {
        "apiVersion": VERSION,
        "kind": "ApplicationSurfaces",
        "notice": NOTICE,
        "webSecurityContract": {"validated": False, "note": CONTRACT_NOTE},
        "engagement": document.get("name"),
        "generatedFrom": {"scopeSha256": report.sha256},
        "authorization": {
            "status": auth.get("status"),
            "approvalId": auth.get("approval_id"),
            "approvedBy": auth.get("approved_by"),
            "validFrom": _time(auth.get("valid_from")),
            "validUntil": _time(auth.get("valid_until")),
            "problems": auth_problems,
        },
        "platform": {
            "name": _answer(platform.get("name")),
            "components": {
                "inScope": [name for name in COMPONENTS if components.get(name) == "in-scope"],
                "outOfScope": [name for name in COMPONENTS if components.get(name) == "out-of-scope"],
                "open": {name: state_of(components.get(name)) for name in COMPONENTS
                         if components.get(name) not in {"in-scope", "out-of-scope"}},
            },
            "outOfScope": _answer(platform.get("out_of_scope")),
            "environment": {
                "kind": _answer(environment.get("kind")),
                "realCustomers": _answer(environment.get("real_customers")),
                "testTenant": _answer(environment.get("test_tenant")),
                "neverTouch": _answer(environment.get("never_touch")),
            },
        },
        "thirdParties": {
            name: {
                "provider": _answer(_section(third, name).get("provider")),
                "permission": _answer(_section(third, name).get("permission")),
                "reference": _answer(_section(third, name).get("reference")),
                "state": "resolved" if facts["thirdParties"][name]["state"] == ANSWERED else "open",
            }
            for name in THIRD_PARTIES
        },
        "dialing": {
            "reach": {name: _answer(_section(dialing, "reach").get(name))
                      for name in [d.get("name") for d in _items(document.get("destinations"))]
                      if isinstance(name, str)},
            "neverDial": _answer(dialing.get("never_dial")),
            "neverDialPrefixes": _answer(dialing.get("never_dial_prefixes")),
            "toll": _answer(dialing.get("toll")),
        },
        "operations": {
            "allowedHours": _answer(operations.get("allowed_hours")),
            "maxConcurrentCalls": _answer(operations.get("max_concurrent_calls")),
            "maxRequestsPerSecond": _answer(operations.get("max_requests_per_second")),
            "blocking": _answer(operations.get("blocking")),
            "emergencyContact": {
                "name": _answer(_section(operations, "emergency_contact").get("name")),
                "channel": _answer(_section(operations, "emergency_contact").get("channel")),
            },
            "stopSignal": _answer(operations.get("stop_signal")),
        },
        "productionSafety": {
            "applies": facts["productionSafety"]["applies"],
            "reason": facts["productionSafety"]["reason"],
            "open": facts["productionSafety"]["open"],
        },
        "addressing": [
            {"name": item.get("name"), "addresses": _answer(item.get("addresses")),
             "shared": _answer(item.get("shared")), "changing": _answer(item.get("changing"))}
            for item in _items(platform.get("addressing"))
        ] if isinstance(platform.get("addressing"), list) else _answer(platform.get("addressing")),
        "surfaces": surfaces if isinstance(application.get("surfaces"), list)
        else _answer(application.get("surfaces")),
        "identities": [
            {"id": item.get("id"), "role": _answer(item.get("role")), "tenant": _answer(item.get("tenant")),
             "credentialRef": _answer(item.get("credential_ref"))}
            for item in _items(application.get("identities"))
        ] if isinstance(application.get("identities"), list) else _answer(application.get("identities")),
        "objectClasses": _answer(application.get("object_classes")),
        "routeInventory": {
            "kind": _answer(inventory.get("kind")),
            "file": inventory.get("file"),
            "provided": inventory.get("kind") in INVENTORY_PROVIDED,
        },
        "summary": {
            state: [item["name"] for item in surfaces if item["state"] == state]
            for state in ("approved", "pending", "undecided", "out-of-scope")
        },
        "openQuestions": [{"id": item["id"], "state": item["state"], "question": item["text"]}
                          for item in facts["open"]],
    }
    record["contentSha256"] = _content_digest(record)
    return record


def dump(record: dict[str, Any]) -> bytes:
    return (HEADER + yaml.safe_dump(record, sort_keys=False, default_flow_style=False,
                                    allow_unicode=True, width=100)).encode()


def existing_state(path: Path) -> str:
    """absent, managed (ours and unedited), edited, or unmanaged."""
    if not path.exists() and not path.is_symlink():
        return "absent"
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 1024 * 1024:
        return "unmanaged"
    try:
        value = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        return "unmanaged"
    if not isinstance(value, dict) or value.get("apiVersion") != VERSION:
        return "unmanaged"
    try:
        return "managed" if value.get("contentSha256") == _content_digest(value) else "edited"
    except (TypeError, ValueError):
        return "edited"


def precheck(root: Path, report: Report, force: bool) -> tuple[bytes | None, list[Finding], list[Finding]]:
    """Decide what compile does with the record, before anything is written.

    Returns ``(data to write or None, skip reasons, refusals)``.
    """
    document = report.document or {}
    if not has_sections(document):
        return None, [], []
    reasons = [item for item in report.findings if item.severity == "error" and ARTIFACT in item.blocks]
    if reasons:
        return None, reasons, []
    path = root / FILENAME
    state = existing_state(path)
    if path.is_symlink():
        return None, [], [Finding("scope.unsafe_path", "error", "invalid", FILENAME, "derivative path is a symlink")]
    if state in {"edited", "unmanaged"} and not force:
        code, why = (("scope.derivative_modified", "was edited after it was generated") if state == "edited"
                     else ("scope.derivative_unmanaged", "exists but was not generated by scope compile"))
        return None, [], [Finding(code, "error", "inconsistent", FILENAME,
                                  f"{FILENAME} {why}; re-run with --force to overwrite it")]
    return dump(build(document, report)), [], []


def finish(root: Path, report: Report, data: bytes | None, write: Callable[..., None]) -> tuple[dict[str, str] | None, list[str]]:
    """Write the record (when there is one) and return ``(generated entry, notes)``."""
    path = root / FILENAME
    notes: list[str] = []
    if data is None:
        if not has_sections(report.document or {}) and existing_state(path) != "absent":
            notes.append(f"{FILENAME} is left from an earlier compile, but the scope no longer has a "
                         "platform or application section; it is out of date and can be deleted")
        return None, notes
    write(path, data, replace=path.exists())
    record = yaml.safe_load(data.decode())
    summary = record["summary"]
    counts = ", ".join(f"{len(summary[state])} {state}" for state in summary)
    # Rehearsal 4, papercut 13: the counts are of web surfaces (question A1),
    # which are none when no web part is in scope. The platform parts the
    # owner answered are counted beside them, so "0, 0, 0, 0" is not read as
    # "nothing was recorded".
    components = (record.get("platform") or {}).get("components") or {}
    parts = (f"platform parts: {len(components.get('inScope') or [])} in scope, "
             f"{len(components.get('outOfScope') or [])} out of scope, "
             f"{len(components.get('open') or {})} not answered; web surfaces: ")
    notes.append(f"{FILENAME} records the platform and web surfaces ({parts}{counts}; "
                 f"{len(record['openQuestions'])} question(s) open). It is a record only: no live "
                 "application runner exists, and nothing in Sippycup sends HTTP to these surfaces")
    return {"artifact": ARTIFACT, "path": str(path), "sha256": hashlib.sha256(data).hexdigest()}, notes


def state_for(root: Path, scope_sha256: str | None, recorded: bool) -> str:
    """not-recorded, not-compiled, current, stale, or edited (local files only)."""
    path = root / FILENAME
    state = existing_state(path)
    if not recorded:
        return "not-recorded" if state == "absent" else "stale"
    if state == "absent":
        return "not-compiled"
    if state != "managed":
        return "edited"
    try:
        value = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return "edited"
    return "current" if (value.get("generatedFrom") or {}).get("scopeSha256") == scope_sha256 else "stale"
